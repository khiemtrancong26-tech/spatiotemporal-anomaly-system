import { test, expect } from '@playwright/test';
async function login(page: import('@playwright/test').Page, username = 'analyst01') {
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill(username);
  await page.getByLabel('Mật khẩu', { exact: true }).fill('demo-password');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
}
test('login, session restoration, workspace filters, logout and admin guard', async ({ page }) => {
  await page.goto('/datasets');
  await expect(page.getByRole('heading', { name: 'Đăng nhập' })).toBeVisible();
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('wrong');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('wrong');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('không đúng');
  await login(page);
  await expect(page.getByRole('link', { name: 'Mở dữ liệu' })).toBeVisible();
  await page.getByLabel('Sắp xếp').selectOption('createdAt:asc');
  await expect(page.getByRole('link', { name: 'Mở dữ liệu' })).toBeVisible();
  await page.getByRole('link', { name: 'Mở dữ liệu' }).click();
  await expect(page.getByRole('heading', { name: 'PM2.5 Sample Dataset' })).toBeVisible();
  await page.getByLabel('Trạm (Sensor ID)').fill('sensor-001');
  await page.getByRole('button', { name: 'Áp dụng bộ lọc' }).click();
  await page.getByRole('button', { name: 'Analysis', exact: true }).click();
  await expect(page.getByTestId('applied-filter')).toContainText('sensor-001');
  await page.getByRole('button', { name: 'Visualization', exact: true }).click();
  await expect(page.getByLabel('Trạm (Sensor ID)')).toHaveValue('sensor-001');
  await page.getByRole('link', { name: 'Datasets', exact: true }).click();
  await page.getByRole('link', { name: 'Mở dữ liệu' }).click();
  await expect(page.getByLabel('Trạm (Sensor ID)')).toHaveValue('sensor-001');
  await page.reload();
  await expect(page.getByText('Chưa có metadata dataset.', { exact: false })).toBeVisible();
  await page.goto('/admin/users');
  await expect(page.getByRole('heading', { name: 'Không có quyền truy cập' })).toBeVisible();
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  await expect(page.getByRole('heading', { name: 'Đăng nhập' })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('pm25.auth.mock'))).toBeNull();
  await login(page, 'admin01');
  await expect(page.getByRole('heading', { name: 'Quản lý tài khoản', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Quản lý tài khoản', exact: true })).toBeVisible();
  await page.goto('/datasets');
  await expect(page.getByRole('link', { name: 'Mở dữ liệu' })).toBeVisible();
  await page.screenshot({ path: 'test-results/m2-desktop.png', fullPage: true });
});
test('mobile layout and deep link survive login without inventing metadata', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/workspace/unknown-dataset');
  await login(page);
  await expect(page.getByText('Dataset ID: unknown-dataset', { exact: true })).toBeVisible();
  await expect(page.getByText('Chưa có metadata dataset.', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/m2-mobile.png', fullPage: true });
});

test('register handles duplicate usernames, returns to login and never auto-authenticates', async ({ page }) => {
  await page.goto('/login');
  await page.getByRole('link', { name: 'Chưa có tài khoản? Đăng ký' }).click();
  await expect(page.getByRole('heading', { name: 'Đăng ký tài khoản' })).toBeVisible();
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('analyst01');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('demo-password');
  await page.getByRole('button', { name: 'Đăng ký', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('đã tồn tại');
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('new-user');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('new-password');
  await page.getByRole('button', { name: 'Đăng ký', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Đăng nhập' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('Đăng ký thành công');
  expect(await page.evaluate(() => sessionStorage.getItem('pm25.auth.mock'))).toBeNull();
  await expect(page.getByLabel('Mật khẩu', { exact: true })).toHaveValue('');
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('new-user');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('new-password');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dữ liệu của bạn' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Quản lý tài khoản' })).toHaveCount(0);
});

test('M5 demo submits one immutable intent, follows async lifecycle and clears context on logout', async ({ page }) => {
  await page.goto('/workspace/dataset-001');
  await login(page);
  await page.getByRole('button', { name: 'Analysis', exact: true }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Gửi analysis', exact: true }).click();
  await expect(page.getByTestId('run-status')).toContainText('queued');
  await expect(page.getByRole('button', { name: 'Thử lại cùng key', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Đọc lại run' }).click();
  await expect(page.getByTestId('run-status')).toContainText('running');
  await page.getByRole('button', { name: 'Đọc lại run' }).click();
  await expect(page.getByTestId('run-status')).toContainText('completed');
  await expect(page.getByRole('button', { name: 'Xem reading-002', exact: true })).toBeVisible();
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(k => k.startsWith('pm25.analysis.')).length)).toBe(1);
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(k => k.startsWith('pm25.analysis.')).length)).toBe(0);
});

test('M7 admin creates, edits and loses admin access after self downgrade', async ({ page }) => {
  await page.goto('/admin/users');
  await login(page, 'admin01');
  await page.getByLabel('Username mới').fill('created-admin');
  await page.getByLabel('Mật khẩu mới').fill('secret-password');
  await page.getByRole('button', { name: 'Tạo user', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Server đã tạo' })).toBeVisible();
  await expect(page.getByLabel('Mật khẩu mới')).toHaveValue('');
  await page.getByRole('button', { name: 'Sửa created-admin', exact: true }).click();
  await page.getByLabel('Role', { exact: true }).selectOption('admin');
  await page.getByRole('button', { name: 'Lưu tài khoản' }).click();
  await expect(page.getByRole('status')).toContainText('xác nhận cập nhật');
  page.on('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Về danh sách user' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'created-admin' })).toContainText('admin');
  await page.screenshot({ path: 'test-results/m7-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/m7-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Sửa admin01', exact: true }).click();
  await page.getByLabel('Role', { exact: true }).selectOption('analyst');
  await page.getByRole('button', { name: 'Lưu tài khoản' }).click();
  await expect(page.getByRole('heading', { name: 'Không có quyền truy cập' })).toBeVisible();
});
